import {it,expect} from 'vitest';
import * as THREE from 'three';
import {coastContactSurface} from '../src/coast-contact-feedback';
import {coastDriveBounds,coastBarrierStoneAt} from '../src/coast-layout';
import {GuardrailContact} from '../src/guardrail-contact';
import {CoastStoneContact} from '../src/coast-stone-contact';
import {createState} from '../src/handling';
import {EngineSound} from '../src/sound';
import {ImpactSparks} from '../src/impact-sparks';

it('distinguishes actual metal, concrete and invisible coast boundaries on both sides',()=>{
 expect(coastContactSurface(500,-1)).toBe('metal');
 expect(coastContactSurface(850,-1)).toBe('metal');
 expect(coastContactSurface(coastBarrierStoneAt(2508,-1).d,-1)).toBe('concrete');
 expect(coastContactSurface(coastBarrierStoneAt(852,1).d,1)).toBe('concrete');
 // Between visible bollards, the fallback is not made of fake stone.
 expect(coastContactSurface(coastBarrierStoneAt(852,1).d+5.5,1)).toBe('soft');
 expect(coastContactSurface(3990,1)).toBe('soft');
 const g=new GuardrailContact(1.15,2.1,d=>coastDriveBounds(d,8.75));
 const s=createState();s.distance=8720;s.lateral=-12;s.speed=70;
 const collision=g.update(s,8719,-10,.016,true);
 expect(collision).toBeGreaterThan(0);
 expect(g.contactSide).toBe(-1);
 expect(g.contactDistance).toBeGreaterThan(8715);
 expect(coastContactSurface(g.contactDistance,g.contactSide)).toBe('metal');
 g.reset();expect(g.contactDistance).toBe(0);
});
it('makes a visible concrete stone the first physical contact before fallback safety wall',()=>{
 const concrete=coastBarrierStoneAt(852,1),s=createState();
 s.distance=concrete.d+6;s.lateral=8.7;s.speed=83;
 const stone=new CoastStoneContact(()=>8.75,1.15,2.1);
 const hit=stone.update(s,{distance:concrete.d-6,lateral:8.7},.12,1);
 expect(hit).toBeDefined();
 const fallback=new GuardrailContact(1.15,2.1,d=>coastDriveBounds(d,8.75));
 expect(fallback.update(s,concrete.d-6,8.7,.12,true)).toBe(0);
});
it('never turns an invisible wall into metallic audio or yellow sparks',()=>{
 const sound=new EngineSound();
 sound.impact(.7,'soft');expect(sound.inspect().lastImpact).toBe('soft');
 sound.impact(.7,'concrete');expect(sound.inspect().lastImpact).toBe('concrete');
 sound.impact(.7,'guardrail');expect(sound.inspect().lastImpact).toBe('guardrail');
 const scene=new THREE.Scene(),fx=new ImpactSparks(scene);
 const p=new THREE.Vector3(),right=new THREE.Vector3(1,0,0),forward=new THREE.Vector3(0,0,1);
 fx.burst(0,p,right,forward,.6,'soft');
 fx.update(.025,p,right,forward,0);
 const soft=fx.inspect().particles;
 expect(fx.inspect().material).toBe('soft');
 expect(soft).toBeGreaterThan(2);
 expect(soft).toBeLessThan(18);
 fx.clear();
 fx.burst(.5,p,right,forward,.6,'concrete');
 fx.update(.525,p,right,forward,0);
 expect(fx.inspect().material).toBe('concrete');
 const gravel=fx.inspect().particles;
 expect(gravel).toBeGreaterThan(soft);
 fx.clear();
 fx.burst(1,p,right,forward,.6,'metal');
 fx.update(1.025,p,right,forward,0);
 expect(fx.inspect().material).toBe('metal');
 expect(fx.inspect().particles).toBeGreaterThan(gravel);
 fx.dispose();expect(scene.children).toHaveLength(0);
});
